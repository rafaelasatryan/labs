import numpy as np

# исходные данные
v = np.array([120, 131, 140, 161, 174, 180, 200, 214, 219, 241, 250, 268, 281, 300], dtype=float)
N = np.array([540, 590, 670, 760, 850, 970, 1070, 1180, 1270, 1390, 1530, 1600, 1780, 2030], dtype=float)

# переход к условным единицам
x = v / 100
y = N / 1000

# квадратичная аппроксимация: y = A*x^2 + B*x + C
A, B, C = np.polyfit(x, y, 2)

print("A =", A)
print("B =", B)
print("C =", C)

# обратный переход к формуле N = a*v^2 + b*v + c
a = A / 10
b = B * 10
c = C * 1000

print("a =", a)
print("b =", b)
print("c =", c)

print(f"N = {a:.7f}*v^2 + {b:.5f}*v + {c:.3f}")